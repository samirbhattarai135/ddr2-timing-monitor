"""Emits net_pkg.vhd: the upstream DDR2 Petri net as VHDL constant tables.

Every arc of the built graph becomes one row. The generic RTL executor
(rtl/petri_monitor.vhd) interprets those rows, so nothing about DDR2 timing is
written by hand.

Dense numbering, shared with the testbench and the trace files:
  transition id = position in sorted transition node indices
  place id      = position in sorted place node indices
  arc id        = position in sorted edge indices

Usage: gen_vhdl.py CONFIG OUT_DIR
Writes OUT_DIR/net_pkg.vhd and OUT_DIR/arcs.tsv (arc id -> readable name).
"""

import sys
from pathlib import Path

from net import (
    Arc, CustomArc, InhibitorArc, ResetArc, TimedArc,
    CONFIGS, build, describe_arc, places, transitions,
)

COMMANDS = ["ACT", "RD", "WR", "RDA", "WRA", "PRE", "PREA", "REF", "PDE", "PDX", "SRE", "SRX"]


def generate(config: str, out_dir: Path) -> None:
    net = build(config)
    graph = net.graph
    memspec = CONFIGS[config]
    n_banks = memspec["nbrOfBanks"]

    trans = transitions(net)
    t_id = {t.index: i for i, t in enumerate(trans)}
    p_nodes = places(net)
    p_id = {p: i for i, p in enumerate(p_nodes)}

    timed_places = set()
    rows = []
    max_bound = 1
    for edge_index in sorted(graph.edge_indices()):
        src, dst = graph.get_edge_endpoints_by_index(edge_index)
        edge = graph.get_edge_data_by_index(edge_index)
        if isinstance(edge, CustomArc):
            bound = int(edge.time_constraint)
            rows.append(("ARC_CUSTOM", t_id[src], t_id[dst], 1, bound))
        elif isinstance(edge, TimedArc):
            bound = int(edge.lower_bound)
            timed_places.add(p_id[src])
            rows.append(("ARC_TIMED", p_id[src], t_id[dst], edge.weight, bound))
        elif isinstance(edge, InhibitorArc):
            rows.append(("ARC_INHIBIT", p_id[src], t_id[dst], edge.weight, 0))
        elif isinstance(edge, ResetArc):
            rows.append(("ARC_RESET", p_id[src], t_id[dst], 1, 0))
        elif isinstance(edge, Arc) and src in p_id:
            rows.append(("ARC_IN", p_id[src], t_id[dst], edge.weight, 0))
        elif isinstance(edge, Arc):
            rows.append(("ARC_OUT", t_id[src], p_id[dst], edge.weight, 0))
        else:
            raise TypeError(f"unhandled arc type {type(edge).__name__}")
        max_bound = max(max_bound, rows[-1][4])

    # Every place except a timed pool is 1-safe in this net (each producer is
    # inhibited by the place it fills); tracegen asserts this on every step.
    init = [len(graph[p].tokens) for p in p_nodes]
    cap = [max(1, n) for n in init]

    t_table = []
    for cmd in COMMANDS:
        per_bank = []
        for b in range(n_banks):
            match = [i for i, t in enumerate(trans) if t.command == cmd and t.bank in (b, None)]
            per_bank.append(match[0])
        t_table.append(per_bank)

    def nat_list(values):
        return ", ".join(f"{i} => {v}" for i, v in enumerate(values))

    arc_lines = ",\n".join(
        f"    {i} => ({k}, {a}, {b}, {w}, {bd})" for i, (k, a, b, w, bd) in enumerate(rows)
    )
    t_rows = ",\n".join(
        f"    {cmd} => ({nat_list(per_bank)})" for cmd, per_bank in zip(COMMANDS, t_table)
    )
    bank_bits = max(1, (n_banks - 1).bit_length())

    pkg = f"""-- GENERATED by tools/gen_vhdl.py from DRAMPyML (third_party/DRAMBench),
-- config "{config}". Do not edit; rerun the generator.
package net_pkg is
  constant CONFIG_NAME : string := "{config}";
  constant N_T     : positive := {len(trans)};
  constant N_P     : positive := {len(p_nodes)};
  constant N_ARC   : positive := {len(rows)};
  constant N_BANKS : positive := {n_banks};
  constant BA_BITS : positive := {bank_bits};
  -- Ages saturate here; it must exceed every bound so "never fired" passes.
  constant AGE_MAX : positive := {max_bound + 1};
  constant TOK_MAX : positive := {max(cap)};

  type arc_kind_t is (ARC_IN, ARC_OUT, ARC_INHIBIT, ARC_RESET, ARC_TIMED, ARC_CUSTOM);
  -- ARC_IN/INHIBIT/RESET/TIMED: src = place, dst = transition.
  -- ARC_OUT: src = transition, dst = place.
  -- ARC_CUSTOM: src = transition, dst = transition; dst is blocked while
  --   (cycles since src last fired) < bound.
  type arc_t is record
    kind   : arc_kind_t;
    src    : natural;
    dst    : natural;
    weight : natural;
    bound  : integer;
  end record;
  type arc_array_t is array (0 to N_ARC - 1) of arc_t;
  type nat_array_t is array (natural range <>) of natural;

  constant ARCS : arc_array_t := (
{arc_lines}
  );
  constant PLACE_INIT  : nat_array_t(0 to N_P - 1) := ({nat_list(init)});
  constant PLACE_CAP   : nat_array_t(0 to N_P - 1) := ({nat_list(cap)});
  constant PLACE_TIMED : boolean_vector(0 to N_P - 1) := ({", ".join(f"{i} => {str(i in timed_places).lower()}" for i in range(len(p_nodes)))});

  type ddr2_cmd_t is ({", ".join(COMMANDS)});
  type bank_t_table_t is array (0 to N_BANKS - 1) of natural;
  type t_table_t is array (ddr2_cmd_t) of bank_t_table_t;
  -- Transition id for (command, bank); rank-level commands repeat one id.
  constant T_ID : t_table_t := (
{t_rows}
  );
end package;
"""
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "net_pkg.vhd").write_text(pkg)
    with open(out_dir / "arcs.tsv", "w") as f:
        for i, edge_index in enumerate(sorted(graph.edge_indices())):
            expr = net.arc_expr.get(edge_index, "")
            f.write(f"{i}\t{describe_arc(net, edge_index)}\t{expr}\n")


if __name__ == "__main__":
    generate(sys.argv[1], Path(sys.argv[2]))
